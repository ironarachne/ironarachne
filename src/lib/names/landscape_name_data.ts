/** Templates are vocabulary records, never claims added to landscape facts. */
export const landscapeTemplates: LandscapeNameTemplate[] = descriptors.map(([epithet, nouns]) => ({
  id: `epithet:${epithet.toLowerCase()}`,
  style: 'descriptive',
  scopes: ['region', 'zone'],
  eligibleNouns: nouns.includes('Mountains') ? [...nouns, 'Range', 'Mountain Range'] : nouns,
  forms: [`the ${epithet} {noun}`],
  motifKey:
    (
      {
        dreaming: 'dream',
        mournful: 'mourn',
        waking: 'wake',
        hushed: 'hush',
        gloaming: 'gloam',
        whispering: 'whisper',
        shrouded: 'shroud',
      } as Record<string, string>
    )[epithet.toLowerCase()] ?? epithet.toLowerCase(),
}));

function addTerrain(
  id: string,
  nouns: string[],
  compounds: string[],
  endings: string[],
  images: string[],
  palette: LandscapeRootPalette,
): void {
  for (const name of compounds) {
    landscapeTemplates.push({
      id: `compound:${name.toLowerCase()}`,
      style: 'compound',
      scopes: ['region'],
      eligibleNouns: nouns.includes('Mountains') ? [...nouns, 'Range', 'Mountain Range'] : nouns,
      forms: [name],
      motifKey: compoundMotif(name),
    });
    landscapeTemplates.push({
      id: `compound-zone:${name.toLowerCase()}`,
      style: 'compound',
      scopes: ['zone'],
      eligibleNouns: nouns.includes('Mountains') ? [...nouns, 'Range', 'Mountain Range'] : nouns,
      forms: endings.some((ending) => name.toLowerCase().endsWith(ending))
        ? [name]
        : [`${name} {noun}`],
      motifKey: compoundMotif(name),
    });
  }
  landscapeTemplates.push({
    id: `compound-root:${id}`,
    style: 'compound',
    scopes: ['region', 'zone'],
    eligibleNouns: nouns.includes('Mountains') ? [...nouns, 'Range', 'Mountain Range'] : nouns,
    forms: endings.map((ending) => `{root}${ending}`),
    rootPalette: palette,
  });
  for (const image of images) {
    const motifKey = image.toLowerCase();
    landscapeTemplates.push(
      {
        id: `image:${id}:${motifKey}`,
        style: 'metaphor',
        scopes: ['region'],
        eligibleNouns: nouns.includes('Mountains') ? [...nouns, 'Range', 'Mountain Range'] : nouns,
        forms: [`the ${image}`, `the ${image.split(' ').at(-1)} of {root}`],
        motifKey,
        rootPalette: palette,
      },
      {
        id: `image-zone:${id}:${motifKey}`,
        style: 'metaphor',
        scopes: ['zone'],
        eligibleNouns: nouns.includes('Mountains') ? [...nouns, 'Range', 'Mountain Range'] : nouns,
        forms: [`the {noun} of the ${image}`],
        motifKey,
      },
    );
  }
}

function compoundMotif(name: string): string {
  const word = name.toLowerCase();
  return (
    [
      'briar',
      'gloam',
      'thorn',
      'hush',
      'dusk',
      'mourn',
      'shade',
      'dream',
      'rain',
      'mist',
      'mire',
      'reed',
      'wind',
      'sere',
      'silt',
      'storm',
      'wyrm',
      'thunder',
      'thirst',
      'dawn',
      'rime',
      'frost',
      'ice',
      'fen',
      'wake',
    ].find((stem) => word.startsWith(stem)) ?? word
  );
}

