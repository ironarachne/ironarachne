function tagsFor(w) {
  const doc = nlp(w);
  return doc.json()[0]?.terms?.[0]?.tags ?? [];
}

const buckets = new Map([
  ['article', new Set()],
  ['noun', new Set()],
  ['verb', new Set()],
  ['adjective', new Set()],
  ['adverb', new Set()],
  ['preposition', new Set()],
  ['pronoun', new Set()],
  ['question', new Set()],
  ['number', new Set()],
  ['interjection', new Set()],
]);

function add(part, w) {
  buckets.get(part)?.add(w);
}

for (const w of lines) {
  if (!/^[a-z]+$/.test(w)) {
    continue;
  }

  const tags = tagsFor(w);

  if (tags.includes('QuestionWord')) {
    add('question', w);
  }
  if (tags.includes('Expression')) {
    add('interjection', w);
  }
  if (tags.includes('Cardinal') || tags.includes('Ordinal') || tags.includes('Multiple')) {
    add('number', w);
  }
  if (tags.includes('Preposition')) {
    add('preposition', w);
  }
  if (tags.includes('Conjunction')) {
    add('preposition', w);
  }
  if (tags.includes('Adverb')) {
    add('adverb', w);
  }
  if (tags.includes('Adjective')) {
    add('adjective', w);
  }

  if (tags.includes('Pronoun') || forcePronoun.has(w)) {
    add('pronoun', w);
  }

  if (tags.includes('Possessive') && ['my', 'your', 'his', 'its', 'our', 'their'].includes(w)) {
    add('pronoun', w);
  }

  const isModal = tags.includes('Modal');
  if (tags.includes('Verb') && !isModal) {
    add('verb', w);
  }

  if (!notNoun.has(w)) {
    add('noun', w);
  }
}

for (const art of ['a', 'an', 'the']) {
  if (lines.includes(art)) {
    add('article', art);
  }
}

const orderedParts = [
  'article',
  'adjective',
  'adverb',
  'preposition',
  'pronoun',
  'question',
  'verb',
  'noun',
  'number',
  'interjection',
];

function toTsArray(name, values) {
  const body = values.map((s) => JSON.stringify(s)).join(',\n  ');
  return `export const ${name} = [\n  ${body},\n] as const;\n`;
}

let out = `/** Generated by scripts/generate_lexicon_frequency_buckets.mjs — do not edit by hand. */\n\n`;

for (const part of orderedParts) {
  const values = [...(buckets.get(part) ?? [])].sort((a, b) => a.localeCompare(b));
  const constName = `POWERLANGUAGE_${part.toUpperCase()}S`;
  out += toTsArray(constName, values);
  out += '\n';
}

const alphaSorted = [...new Set(lines.filter((w) => /^[a-z]+$/.test(w)))].sort((a, b) =>
  a.localeCompare(b),
);
out += toTsArray('POWERLANGUAGE_ALPHABETIC', alphaSorted);

fs.writeFileSync(outPath, out, 'utf8');
