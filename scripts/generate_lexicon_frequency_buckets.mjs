import nlp from 'compromise';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const srcPath = path.join(root, 'src/lib/languages/data/powerlanguage_1000.txt');
const outPath = path.join(root, 'src/lib/languages/lexicon_powerlanguage_bucket_lists.ts');

const raw = fs.readFileSync(srcPath, 'utf8');
const lines = raw
  .split(/\n/)
  .map((s) => s.trim().toLowerCase())
  .filter(Boolean);

